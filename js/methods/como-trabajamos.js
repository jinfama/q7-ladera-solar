/* como-trabajamos.js — the methods section of the Atlas Agrario de América Latina.

   It answers, for the crop series this atlas is built on, the question a historian asks first:
   which of these numbers did a source actually record, and which did the project work out --
   with what method and from what source.

   Everything on screen is read from data/provenance/, generated by
     docs/visores_2026-09/tools/prep_provenance_latam.py   (vocabulary translation)
     docs/visores_2026-09/tools/build_provenance.py        (the panels' data contract)
   out of 05_projects/latam/data/final/crop_panel.csv, which is where the viewer's own
   agriculture.json comes from. No figure below is typed by hand: if the panel changes
   upstream, this section changes with it.

   Two things this section must NOT do, and does not:
     - it does not claim the viewer distinguishes observed from estimated. It does not.
       Nothing in the map, the ranking, the treemap or the table carries these flags; they
       exist in the source panel and stop at the converters. The limits say so.
     - it does not extend the claim beyond crops. Trade, land use, livestock, labour and
       inequality have provenance of very different quality, and are named one by one.

   NOTA PARA JUAN: la prosa de PROSE es un BORRADOR escrito por el agente el 2026-09-05, a
   revisar. Las cifras entre {llaves} se rellenan solas desde panel.json e index.json, así que
   puedes reescribir el texto sin miedo a que los números se queden viejos.
*/

import ProvenancePanel from './provenance-panel.js?v=20260908b';

const N = (v) => new Intl.NumberFormat('es-ES').format(v);
const PCT = (v) => new Intl.NumberFormat('es-ES', { maximumFractionDigits: 1 }).format(v);
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

/* Placeholders in {curly braces} are filled at render time. Never write a number here. */
const PROSE = `
<p>Este atlas dibuja series anuales de producción agraria para <b>{paises} países</b> de América
Latina entre <b>{y0} y {y1}</b>. Nadie contó la cosecha de cada cultivo, en cada país, todos los
años de ese siglo largo. Lo que existe son <b>recuentos desiguales</b>: los anuarios de la FAO
desde 1961, los de la Sociedad de Naciones entre guerras, censos y anuarios nacionales sueltos, y
las series históricas que el propio proyecto ha reconstruido para el periodo anterior. Entre
unos y otros quedan huecos de décadas.</p>

<p>El panel de cultivos que alimenta a este visor tiene <b>{celdas} celdas</b> de país × año ×
cultivo, con <b>{cultivos} cultivos</b>. De todas ellas, <b>{observadas} ({pct} %) llevan la
etiqueta «original»</b>: una fuente las registró. El resto son decisiones del proyecto, y
conviene separar dos tipos muy distintos de decisión.</p>

<p>La primera es <b>rellenar un hueco</b> entre dos observaciones, o extender la serie hacia
atrás. Cuando el hueco es corto se interpola linealmente; cuando hay que retroceder más allá del
primer dato se usa el crecimiento de otra serie como guía —la población del país, o sus
exportaciones del mismo producto— para no dibujar una recta plana durante cuarenta años.</p>

<p>La segunda es <b>escribir un cero</b>. Cuando una fuente no trae fila para un cultivo en un
país y un año, el panel anota cero. Es lo razonable —Chile no producía café— pero <b>es una
convención, no una lectura</b>: si esos ceros se contaran como dato observado, la cobertura del
atlas saltaría del {pct} % a más de las cuatro quintas partes sin que nadie hubiera contado nada
nuevo. Aquí se cuentan como estimación, con el método <i>cero estructural</i>. Es la razón
principal de que la cifra global de arriba parezca tan baja.</p>

<p>Los cinco paneles de abajo enseñan esa diferencia sin suavizarla: <b>punto sólido</b> donde
hay dato observado, <b>trazo discontinuo</b> —de un color por método— donde hay estimación, y
<b>hueco</b>, nunca una recta, donde no hay ninguna de las dos. Pasa el ratón o toca cualquier
año y verás de dónde sale. El interruptor «ver solo los años observados» deja en pantalla el
esqueleto documental desnudo, que es la prueba más honesta de qué sostiene cada serie.</p>

<p>No son las cinco mejores series: son las que marcan el rango. El café de Brasil está
observado en los {n_anos} años, de punta a punta; el plátano de Perú, en poco más de uno de cada
diez. Debajo de ellas, la <b>matriz de cobertura</b> repite el reparto para {matriz_series}
combinaciones de país y cultivo, año a año, y ahí se ve de un vistazo qué países entran tarde en
las estadísticas y qué cultivos son cero estructural durante todo el siglo.</p>
`;

/* The honest part. Written from what was actually checked on 2026-09-05, not from what would
   be convenient. Anything that changes upstream has to change here too. */
function limits(idx, panel) {
    const raros = (idx.metodos_no_canonicos || []).filter(m => m !== 'observed');
    return `
      <div class="pv-limits">
        <h3>Lo que este visor todavía NO hace</h3>
        <ul>
          <li><b>El visor no distingue observado de estimado.</b> Es el límite más importante y
              conviene decirlo con todas las letras: los datos que sirven el mapa, el ranking,
              el treemap y la tabla —<code>agriculture.json</code> y sus hermanos— <b>no llevan
              ninguna marca de procedencia por celda</b>. Las etiquetas existen en el panel de
              origen (<code>method_prod</code>, <code>source_prod</code>,
              <code>source_quality_prod</code> en <code>crop_panel.csv</code>) y se pierden en
              los conversores. Esta sección es hoy el único sitio del visor donde se ven, y lo
              hace leyendo el panel de origen, no lo que el visor sirve. Mientras eso siga así,
              <b>ningún valor del mapa dice si alguien lo contó</b>.</li>
          <li><b>Qué haría falta para arreglarlo.</b> Que los diez conversores de
              <code>build/</code> escriban, junto a cada serie de valores, un array paralelo de
              banderas —observado / estimado / sin dato— y el método; y que las vistas lo pinten,
              como ya hacen los paneles de aquí abajo. Es trabajo de <i>build</i>, no de
              interfaz: el dato ya existe.</li>
          <li><b>Solo cultivos.</b> Lo de arriba vale para producción agrícola y para nada más.
              El comercio se construye desde <code>trade_final_energy.csv</code>, que no trae
              columnas de procedencia, aunque su hermano <code>trade_final.csv</code> sí las
              tiene (<code>method_value</code>, <code>source</code>,
              <code>confidence_tier</code>): cambiar de fichero de entrada bastaría. El uso del
              suelo trae la fuente de cada variable pero <b>ninguna bandera explícita</b> de
              observado o estimado, así que aquí no se ha inventado una. Ganadería, trabajo y
              desigualdad vienen de módulos externos y quedan fuera de esta sección hasta que se
              revisen uno a uno.</li>
          <li><b>Un cero no es una observación.</b> ${N(idx.metodos?.structural_zero ?? 0)}
              celdas de las que se ven aquí
              son ceros impuestos porque la fuente no traía fila. Están dibujados como estimación
              y etiquetados «cero estructural». Casi siempre serán correctos; no son un dato.</li>
          <li><b>No hay años donantes.</b> A diferencia del atlas andaluz, un valor interpolado
              de este panel <b>no guarda entre qué dos observaciones se calculó</b>, así que el
              tooltip no puede enseñarlo y la cuenta no se puede rehacer desde el visor. Está en
              el pipeline, no en el dato publicado.</li>
          <li><b>La confianza es del valor, no de la fuente.</b> Un anuario mal levantado sigue
              siendo dato observado. Marcar algo como observado dice de dónde viene, no que sea
              correcto.</li>
          ${raros.length ? `<li>Hay métodos fuera del vocabulario canónico de la ficha de
              procedencia (<code>${raros.map(esc).join('</code>, <code>')}</code>): se muestran
              tal cual, con su nombre, para que se puedan reconciliar aguas arriba en vez de
              esconderlos.</li>` : ''}
        </ul>
        <p class="pv-note">Panel de origen: <code>${esc(panel.fuente || '')}</code>.</p>
      </div>`;
}

function fill(tpl, idx, panel, series) {
    const map = {
        paises: N(panel.paises), cultivos: N(panel.cultivos),
        y0: panel.anos?.[0] ?? '', y1: panel.anos?.[1] ?? '',
        celdas: N(panel.celdas), observadas: N(panel.observadas),
        estimadas: N(panel.estimadas), pct: PCT(panel.pct_observado),
        n_anos: N(series[0]?.years?.length ?? 0),
        matriz_series: N(idx.series_totales ?? 0),
    };
    return tpl.replace(/\{(\w+)\}/g, (m, k) => (k in map ? map[k] : m));
}

function headline(panel, idx) {
    return `
      <div class="pv-headline">
        <div><b>${N(panel.celdas)}</b><span>celdas de país × año × cultivo</span></div>
        <div><b>${PCT(panel.pct_observado)} %</b><span>con etiqueta «original»</span></div>
        <div><b>${N(idx.metodos?.structural_zero ?? 0)}</b><span>ceros estructurales en las series mostradas</span></div>
        <div><b>0</b><span>banderas de procedencia en los JSON que sirve el visor</span></div>
      </div>`;
}

function sourcesTable(idx) {
    const rows = Object.entries(idx.fuentes || {}).sort((a, b) => b[1] - a[1]);
    if (!rows.length) return '';
    return `
      <div class="pv-sources">
        <h3>De dónde salen los valores de las cinco series</h3>
        <table><tbody>
          ${rows.map(([k, v]) => `<tr><td>${esc(k)}</td><td>${N(v)} celdas</td></tr>`).join('')}
        </tbody></table>
      </div>`;
}

const ComoTrabajamos = {
    _done: false,

    /** Idempotent: safe to call every time the tab is opened. */
    async render(host) {
        if (!host || this._done) return;
        this._done = true;
        try {
            const base = 'data/provenance';
            const [{ index, series, coverage }, panel] = await Promise.all([
                ProvenancePanel.load(base),
                fetch(`${base}/panel.json`).then(r => r.json()),
            ]);
            index.series_totales = coverage ? coverage.territories.length : 0;

            host.innerHTML = `
              <div class="pv-section">
                <h2>Cómo trabajamos</h2>
                <p class="pv-draft"><b>Borrador.</b> El texto de esta sección está pendiente de
                   revisión del autor; las cifras se leen de los datos y están al día.</p>
                <div class="pv-prose">${fill(PROSE, index, panel, series)}</div>
                ${headline(panel, index)}
                <h3 style="margin:26px 0 12px">Cinco series, del techo al suelo de la cobertura</h3>
                <div class="pv-grid" id="pv-series"></div>
                <h3 style="margin:30px 0 10px">Cobertura de las cuatro familias de cultivo</h3>
                <div id="pv-coverage"></div>
                ${limits(index, panel)}
                ${sourcesTable(index)}
              </div>`;

            const grid = host.querySelector('#pv-series');
            series
                .sort((a, b) => b.cobertura.pct_observado - a.cobertura.pct_observado)
                .forEach(s => {
                    const box = document.createElement('div');
                    grid.appendChild(box);
                    ProvenancePanel.renderSeries(box, s);
                });

            if (coverage) ProvenancePanel.renderCoverage(host.querySelector('#pv-coverage'), coverage);
        } catch (err) {
            this._done = false;   // let the next open retry
            host.innerHTML =
                `<div class="pv-section"><p class="pv-empty">No se pudo cargar la procedencia ` +
                `(${esc(err.message)}). Los datos viven en <code>data/provenance/</code>.</p></div>`;
            console.error('como-trabajamos:', err);
        }
    },
};

export default ComoTrabajamos;
